// ใช้ค่าชุดนี้ร่วมกัน → การ์ดกว้างเท่ากัน + ระยะห่างระหว่างการ์ดเท่ากัน (หน้าสินค้าทั้งหมดมีแถบหมวดหมู่ — ดู PRODUCT_LIST_*)
//
//   ขอบซ้าย-ขวา 12 / 24 (≥640) / 32 (≥1280) · ระยะห่างระหว่างการ์ด gap-3 = 13.5px (ฐาน 18px) ทุกขนาดจอ
//   คอลัมน์ 2 / 3 (≥640) / 5 (≥1280)
//   ≥1280 กรอบกว้าง 1200 คงที่ → การ์ดกว้าง (1200 − 2×32 − 4×13.5) / 5 = 216.4px เสมอ
// ─────────────────────────────────────────────────────────────

/** ขอบซ้าย-ขวาของส่วนการ์ดสินค้า */
export const PRODUCT_SECTION_PX = "px-[12px] sm:px-[24px] xl:px-[32px]";

/** container ของส่วนการ์ดสินค้า (กว้างสุด 1200 เท่าหน้าอื่น) */
export const PRODUCT_SECTION = `w-full max-w-[1200px] mx-auto ${PRODUCT_SECTION_PX}`;

/** ระยะห่างระหว่างการ์ด — ค่าเดียวทุกขนาดจอ */
export const PRODUCT_GRID_GAP = "gap-3";

/**
 * การ์ดสินค้าเต็มความกว้าง — มือถือ 2 · 640–1279 3 · ≥1280 5 คอลัมน์
 * จัดแบบ masonry (CSS columns): การ์ดสูงตามเนื้อหา และแต่ละใบห่างจากใบด้านบนเท่ากันทุกใบ (ไม่มีช่องว่างใต้ใบที่เตี้ยกว่า)
 * ลำดับการ์ดเรียงลงตามคอลัมน์ · การ์ดแต่ละใบต้องใส่ PRODUCT_MASONRY_ITEM (ระยะห่างแนวตั้ง + ไม่ถูกตัดข้ามคอลัมน์)
 */
export const PRODUCT_GRID = `columns-2 sm:columns-3 xl:columns-5 ${PRODUCT_GRID_GAP}`;

/** ใส่ที่การ์ดแต่ละใบในคอลัมน์ masonry — mb-3 = ระยะห่างแนวตั้งเท่า gap-3 แนวนอน */
export const PRODUCT_MASONRY_ITEM = "mb-3 break-inside-avoid";

/**
 * หน้าสินค้าทั้งหมด — ขอบเท่าหน้าแรก + จัดแถวเป็นคอลัมน์ชุดเดียวกับหน้าแรก → การ์ดกว้างเท่าหน้าแรกพอดีทุกขนาดจอ
 *   <1024  : หมวดหมู่อยู่ด้านบน · สินค้าใช้ PRODUCT_GRID เต็มความกว้าง (2 / 3 คอลัมน์)
 *   ≥1024  : แถวแบ่ง 3 คอลัมน์ (≥1280: 5) เท่าหน้าแรก — หมวดหมู่กิน 1 คอลัมน์ · สินค้ากินที่เหลือ (2 / 4)
 *            grid ซ้อนข้างในกว้าง n คอลัมน์ + (n−1) ช่องว่างพอดี → การ์ดกว้างเท่าคอลัมน์หน้าแรก
 */
export const PRODUCT_LIST_LAYOUT = `flex flex-col gap-6 lg:grid lg:grid-cols-3 xl:grid-cols-5 lg:gap-3 items-start`; // lg:gap-3 = PRODUCT_GRID_GAP (เขียนตรง ๆ ให้ Tailwind สแกนเจอ)
export const PRODUCT_LIST_MAIN = "w-full lg:col-span-2 xl:col-span-4";
// หน้าสินค้าทั้งหมด = grid ปกติ (ไม่ใช่ masonry) — การ์ดในแถวเดียวกันสูงเท่ากัน ปุ่ม "เพิ่มลงตะกร้า" อยู่ระดับเดียวกัน
// (masonry ทำให้การ์ดเหลื่อมกันจนดูไม่เป็นแถว) · [&>*]:mb-0 = ยกเลิก mb-3 ของ PRODUCT_MASONRY_ITEM (grid มี gap แล้ว)
export const PRODUCT_LIST_GRID = `grid grid-cols-2 sm:grid-cols-3 lg:grid-cols-2 xl:grid-cols-4 ${PRODUCT_GRID_GAP} [&>*]:mb-0`;

/**
 * ดึงส่วนสินค้าคล้ายกันออกจากขอบของหน้ารายละเอียดสินค้า (20/32/40/64) ให้ชนขอบเดียวกับ PRODUCT_SECTION_PX
 * → การ์ดกว้างเท่าหน้าแรก โดยไม่ต้องเปลี่ยนขอบของเนื้อหาอื่นในหน้านั้น
 */
export const PRODUCT_GRID_BLEED = "-mx-[8px] md:-mx-[16px] xl:-mx-[32px]";
